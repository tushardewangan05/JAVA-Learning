package Basics;

public class VariablesBasics {
    public static void main(String[] args) {
        int x;
        x = 5; //decleation
        System.out.println(x);
        x = 6;
        System.out.println(x);

        int y; //decleation
        y = 20; //initialization
        System.out.println(y);

        x = 7;
        System.out.println(x);

        x = x-2;
        System.out.println(x);

        x = x+20;
        System.out.println(x);

        x = x-30;
        System.out.println(x);

        x = x*10;
        System.out.println(x);

        x = x/25;
        System.out.println(x);
    }
}